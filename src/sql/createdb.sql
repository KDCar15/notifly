-- Procedimiento
CREATE OR REPLACE PROCEDURE auditoria.sp_registrar_historial(
    IN p_id_nota INT
)
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO auditoria.historial_notas(id_nota)
    VALUES (p_id_nota)
    ON CONFLICT (id_nota)
    DO UPDATE
    SET fecha_acceso = CURRENT_TIMESTAMP;
END;
$$;

-- Trigger para el checklist

CREATE OR REPLACE FUNCTION gestion.fn_crear_checklists()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO gestion.checklists(
        id_nota,
        nombre_checklist
    )
    VALUES
        (NEW.id_nota, 'Checklist 1'),
        (NEW.id_nota, 'Checklist 2');

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_crear_checklists
AFTER INSERT ON gestion.notas
FOR EACH ROW
EXECUTE FUNCTION gestion.fn_crear_checklists();