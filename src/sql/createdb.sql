-- Schema gestion

DROP SCHEMA IF EXISTS gestion CASCADE;
CREATE SCHEMA gestion;

DROP TABLE IF EXISTS gestion.tipos_nota CASCADE;
CREATE TABLE gestion.tipos_nota(
    id_tiponota INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,nombre_tipo VARCHAR(30)
        NOT NULL
        UNIQUE

    ,CONSTRAINT PK_tiponota
        PRIMARY KEY(id_tiponota)
);

DROP TABLE IF EXISTS gestion.estados_nota CASCADE;
CREATE TABLE gestion.estados_nota(
    id_estadonota INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,nombre_estado VARCHAR(30)
        NOT NULL
        UNIQUE

    ,CONSTRAINT PK_estadonota
        PRIMARY KEY(id_estadonota)
);

DROP TABLE IF EXISTS gestion.clasificaciones CASCADE;
CREATE TABLE gestion.clasificaciones(
    id_clasificacion INT
        GENERATED BY DEFAULT AS IDENTITY
    ,nombre_clasificacion VARCHAR(30)
        NOT NULL
        UNIQUE

    ,CONSTRAINT PK_clasificacion
        PRIMARY KEY(id_clasificacion)
);

DROP TABLE IF EXISTS gestion.areas CASCADE;
CREATE TABLE gestion.areas(
    id_area INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,nombre_area VARCHAR(30)
    ,es_facultad BOOLEAN
        DEFAULT false

    ,CONSTRAINT PK_area
        PRIMARY KEY(id_area)
);

DROP TABLE IF EXISTS gestion.contactos CASCADE;
CREATE TABLE gestion.contactos(
    id_contacto INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,id_area INT
        NULL
    ,nombresApellidos VARCHAR(120)
        NOT NULL
    ,ocupacion VARCHAR(60)
        NOT NULL
    ,celular VARCHAR(30)
        NULL
    ,correo VARCHAR(60)
        NULL

    ,CONSTRAINT PK_contacto
        PRIMARY KEY(id_contacto)
    ,CONSTRAINT FK_area
        FOREIGN KEY(id_area)
        REFERENCES gestion.areas(id_area)
);

DROP TABLE IF EXISTS gestion.notas CASCADE;
CREATE TABLE gestion.notas(
    id_nota INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,id_estadonota INT
        NOT NULL
        DEFAULT 1
    ,id_tiponota INT
        NOT NULL
    ,id_clasificacion INT
        NOT NULL
    ,id_area INT
        NULL
    ,nombresApellidos VARCHAR(120)
        NOT NULL
    ,correo VARCHAR(30)
        NOT NULL
    ,celular VARCHAR(30)
        NOT NULL
    ,fechahora TIMESTAMP
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP
    ,descripcion VARCHAR
        NOT NULL

    ,CONSTRAINT PK_nota
        PRIMARY KEY(id_nota)
    ,CONSTRAINT FK_estadonota
        FOREIGN KEY(id_estadonota)
        REFERENCES gestion.estados_nota(id_estadonota)
    ,CONSTRAINT FK_tiponota
        FOREIGN KEY(id_tiponota)
        REFERENCES gestion.tipos_nota(id_tiponota)
    ,CONSTRAINT FK_clasificacion
        FOREIGN KEY(id_clasificacion)
        REFERENCES gestion.clasificaciones(id_clasificacion)
    ,CONSTRAINT FK_area
        FOREIGN KEY(id_area)
        REFERENCES gestion.areas(id_area)
);

CREATE TABLE gestion.checklists(
    id_checklist INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,id_nota INT
        NOT NULL
    ,nombre_checklist VARCHAR(60)
        NOT NULL
    ,completado BOOLEAN
        NOT NULL
        DEFAULT FALSE
    ,CONSTRAINT PK_checklist
        PRIMARY KEY(id_checklist)
    ,CONSTRAINT FK_nota_checklist
        FOREIGN KEY(id_nota)
        REFERENCES gestion.notas(id_nota)
        ON DELETE CASCADE
);

-- Schema Auditoria
DROP SCHEMA IF EXISTS auditoria CASCADE;
CREATE SCHEMA auditoria;

DROP TABLE IF EXISTS auditoria.accion CASCADE;
CREATE TABLE auditoria.accion(
    id_accion INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,nombre_accion VARCHAR(30)
