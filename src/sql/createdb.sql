CREATE TABLE auditoria.historial_notas(
    id_historial INT
        NOT NULL
        GENERATED BY DEFAULT AS IDENTITY
    ,id_nota INT
        NOT NULL
    ,fecha_acceso TIMESTAMP
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP
    
    ,CONSTRAINT PK_historial
        PRIMARY KEY(id_historial)
    ,CONSTRAINT FK_nota
        FOREIGN KEY(id_nota)
        REFERENCES gestion.notas(id_nota)
    ,CONSTRAINT UQ_nota
        UNIQUE(id_nota)
);

