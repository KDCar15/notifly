        NOT NULL
    ,id_registro INT
        NOT NULL
    ,columna TEXT
        NULL
    ,fechahora TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP
    ,id_accion INT
    

    ,CONSTRAINT PK_seguimiento
